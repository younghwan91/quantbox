"""
Event-driven architecture for unified backtest/live trading.

This module implements the event system that allows the same strategy logic
to work identically in both backtesting and live trading modes.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Optional, Dict, Any, List
from queue import Queue
import uuid


class EventType(Enum):
    """Types of events in the trading system."""
    MARKET = "MARKET"  # New market data available
    SIGNAL = "SIGNAL"  # Strategy generated a signal
    ORDER = "ORDER"    # Order to be executed
    FILL = "FILL"      # Order was filled
    RISK = "RISK"      # Risk management event
    POSITION = "POSITION"  # Position update
    PORTFOLIO = "PORTFOLIO"  # Portfolio update


class SignalType(Enum):
    """Types of trading signals."""
    LONG = "LONG"
    SHORT = "SHORT"
    EXIT_LONG = "EXIT_LONG"
    EXIT_SHORT = "EXIT_SHORT"
    CLOSE_ALL = "CLOSE_ALL"


class OrderType(Enum):
    """Types of orders."""
    MARKET = "MARKET"
    LIMIT = "LIMIT"
    STOP = "STOP"
    STOP_LIMIT = "STOP_LIMIT"


class OrderSide(Enum):
    """Order side."""
    BUY = "BUY"
    SELL = "SELL"


@dataclass
class Event:
    """Base event class."""
    type: EventType
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    event_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    
    def __post_init__(self):
        if isinstance(self.timestamp, str):
            self.timestamp = datetime.fromisoformat(self.timestamp)


@dataclass
class MarketEvent(Event):
    """
    Event triggered when new market data is available.
    """
    type: EventType = EventType.MARKET
    symbol: str = ""
    data: Dict[str, Any] = field(default_factory=dict)
    
    # OHLCV data
    open: float = 0.0
    high: float = 0.0
    low: float = 0.0
    close: float = 0.0
    volume: float = 0.0


@dataclass
class SignalEvent(Event):
    """
    Event generated by strategy indicating a trading signal.
    """
    type: EventType = EventType.SIGNAL
    signal_type: SignalType = SignalType.LONG
    
    # Pair trading specific
    symbol1: str = ""
    symbol2: str = ""
    
    # Signal strength and direction
    strength: float = 1.0  # Signal strength/confidence
    z_score: float = 0.0
    hedge_ratio: float = 1.0
    
    # Strategy metadata
    strategy_id: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class OrderEvent(Event):
    """
    Event representing an order to be sent to execution.
    """
    type: EventType = EventType.ORDER
    order_type: OrderType = OrderType.MARKET
    side: OrderSide = OrderSide.BUY
    
    symbol: str = ""
    quantity: float = 0.0
    price: Optional[float] = None  # For limit orders
    stop_price: Optional[float] = None  # For stop orders
    
    # Order management
    order_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    parent_order_id: Optional[str] = None  # For bracket orders
    
    # Time in force
    time_in_force: str = "GTC"  # GTC, IOC, FOK
    
    # Pair trading specific
    is_pair_order: bool = False
    pair_symbol: str = ""  # The other symbol in the pair
    hedge_ratio: float = 1.0


@dataclass
class FillEvent(Event):
    """
    Event representing a filled order.
    """
    type: EventType = EventType.FILL
    
    order_id: str = ""
    symbol: str = ""
    side: OrderSide = OrderSide.BUY
    
    # Fill details
    fill_quantity: float = 0.0
    fill_price: float = 0.0
    commission: float = 0.0
    slippage: float = 0.0
    
    # Execution metadata
    exchange_order_id: str = ""
    execution_time: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    
    @property
    def total_cost(self) -> float:
        """Total cost including commission and slippage."""
        base_cost = self.fill_quantity * self.fill_price
        return base_cost + self.commission + self.slippage


@dataclass
class RiskEvent(Event):
    """
    Event for risk management alerts.
    """
    type: EventType = EventType.RISK
    
    risk_type: str = ""  # e.g., "MAX_DRAWDOWN", "POSITION_LIMIT", "STOP_LOSS"
    symbol: str = ""
    current_value: float = 0.0
    threshold: float = 0.0
    action: str = ""  # e.g., "CLOSE_POSITION", "REDUCE_SIZE", "ALERT"
    message: str = ""


@dataclass
class PositionEvent(Event):
    """
    Event representing a position update.
    """
    type: EventType = EventType.POSITION
    
    symbol: str = ""
    quantity: float = 0.0
    avg_price: float = 0.0
    current_price: float = 0.0
    unrealized_pnl: float = 0.0
    realized_pnl: float = 0.0
    
    @property
    def market_value(self) -> float:
        """Current market value of position."""
        return self.quantity * self.current_price


class EventQueue:
    """
    Thread-safe event queue for managing trading events.
    """
    
    def __init__(self, maxsize: int = 0):
        self._queue: Queue = Queue(maxsize=maxsize)
        self._handlers: Dict[EventType, List[callable]] = {
            event_type: [] for event_type in EventType
        }
    
    def put(self, event: Event):
        """Add event to queue."""
        self._queue.put(event)
    
    def get(self, block: bool = True, timeout: float = None) -> Event:
        """Get event from queue."""
        return self._queue.get(block=block, timeout=timeout)
    
    def empty(self) -> bool:
        """Check if queue is empty."""
        return self._queue.empty()
    
    def register_handler(self, event_type: EventType, handler: callable):
        """Register an event handler for a specific event type."""
        self._handlers[event_type].append(handler)
    
    def process(self, event: Event):
        """Process an event by calling all registered handlers."""
        for handler in self._handlers[event.type]:
            handler(event)
    
    def process_all(self):
        """Process all events in the queue."""
        while not self.empty():
            event = self.get(block=False)
            self.process(event)


def create_pair_signal(
    symbol1: str,
    symbol2: str,
    signal_type: SignalType,
    z_score: float,
    hedge_ratio: float,
    strategy_id: str = "",
    **kwargs
) -> SignalEvent:
    """
    Factory function to create a pair trading signal event.
    """
    return SignalEvent(
        signal_type=signal_type,
        symbol1=symbol1,
        symbol2=symbol2,
        z_score=z_score,
        hedge_ratio=hedge_ratio,
        strength=min(1.0, abs(z_score) / 3.0),  # Normalize strength
        strategy_id=strategy_id,
        metadata=kwargs
    )


def create_pair_orders(
    signal: SignalEvent,
    capital: float,
    price1: float,
    price2: float,
    fee_rate: float = 0.0005
) -> List[OrderEvent]:
    """
    Create pair of orders from a signal event.
    
    Returns two OrderEvents - one for each leg of the pair trade.
    """
    hedge_ratio = signal.hedge_ratio
    effective_capital = capital * (1 - 2 * fee_rate)
    
    # Calculate quantities
    qty1_value = effective_capital / (1 + hedge_ratio)
    qty2_value = hedge_ratio * qty1_value
    
    qty1 = qty1_value / price1
    qty2 = qty2_value / price2
    
    # Determine sides based on signal type
    if signal.signal_type == SignalType.LONG:
        # Long spread: buy symbol1, sell symbol2
        side1 = OrderSide.BUY
        side2 = OrderSide.SELL
    else:  # SHORT
        # Short spread: sell symbol1, buy symbol2
        side1 = OrderSide.SELL
        side2 = OrderSide.BUY
    
    order1 = OrderEvent(
        symbol=signal.symbol1,
        side=side1,
        quantity=qty1,
        is_pair_order=True,
        pair_symbol=signal.symbol2,
        hedge_ratio=hedge_ratio
    )
    
    order2 = OrderEvent(
        symbol=signal.symbol2,
        side=side2,
        quantity=qty2,
        is_pair_order=True,
        pair_symbol=signal.symbol1,
        hedge_ratio=1.0 / hedge_ratio
    )
    
    # Link orders
    order1.parent_order_id = signal.event_id
    order2.parent_order_id = signal.event_id
    
    return [order1, order2]
